// pnpm setup:local — wires a running local Supabase (supabase start) to the app:
//   * .env.local with URL/keys for Vite and the scripts
//   * supabase/functions/.env with VAPID keys and the cron dispatch secret
//   * demo owner accounts for every studio (passwords saved to .env.local, not printed)
// Safe to re-run: existing values are kept.
import { execSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import webpush from 'web-push';
import { ROOT, listTenantSlugs } from './lib/tenants.ts';

function readEnv(file: string): Map<string, string> {
  const m = new Map<string, string>();
  if (!fs.existsSync(file)) return m;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const x = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (x) m.set(x[1]!, x[2]!);
  }
  return m;
}
function writeEnv(file: string, m: Map<string, string>, header: string) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${header}\n${[...m].map(([k, v]) => `${k}=${v}`).join('\n')}\n`);
}

let status: Record<string, string>;
try {
  status = JSON.parse(execSync('supabase status -o json', { cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore'] }).toString());
} catch {
  console.error('Локальный Supabase не запущен. Выполните: supabase start');
  process.exit(1);
}

const envFile = path.join(ROOT, '.env.local');
const env = readEnv(envFile);
const vapid = env.get('VITE_VAPID_PUBLIC_KEY') ? null : webpush.generateVAPIDKeys();
env.set('VITE_SUPABASE_URL', status.API_URL!);
env.set('VITE_SUPABASE_ANON_KEY', status.ANON_KEY!);
env.set('SUPABASE_URL', status.API_URL!);
env.set('SUPABASE_SERVICE_ROLE_KEY', status.SERVICE_ROLE_KEY!);
env.set('DATABASE_URL', status.DB_URL!);
if (vapid) env.set('VITE_VAPID_PUBLIC_KEY', vapid.publicKey);

const fnFile = path.join(ROOT, 'supabase', 'functions', '.env');
const fnEnv = readEnv(fnFile);
if (vapid) {
  fnEnv.set('VAPID_PUBLIC_KEY', vapid.publicKey);
  fnEnv.set('VAPID_PRIVATE_KEY', vapid.privateKey);
}
if (!fnEnv.get('VAPID_SUBJECT')) fnEnv.set('VAPID_SUBJECT', 'mailto:owner@example.com');
if (!fnEnv.get('DISPATCH_SECRET')) fnEnv.set('DISPATCH_SECRET', crypto.randomBytes(24).toString('hex'));
for (const k of ['LLM_BASE_URL', 'LLM_API_KEY', 'LLM_MODEL']) if (!fnEnv.has(k)) fnEnv.set(k, '');
if (!fnEnv.has('LLM_TOOL_MODE')) fnEnv.set('LLM_TOOL_MODE', 'auto');

for (const slug of listTenantSlugs()) {
  const key = `OWNER_${slug.toUpperCase().replace(/-/g, '_')}`;
  if (!env.get(`${key}_PASSWORD`)) {
    env.set(`${key}_EMAIL`, `owner@${slug}.test`);
    env.set(`${key}_PASSWORD`, crypto.randomBytes(10).toString('base64url'));
  }
}
writeEnv(envFile, env, '# Generated by pnpm setup:local for the LOCAL Supabase stack. Never commit.');
writeEnv(fnFile, fnEnv, '# Edge function secrets for local dev (supabase functions serve). Never commit.');
console.log('✓ .env.local и supabase/functions/.env');

for (const slug of listTenantSlugs()) {
  const key = `OWNER_${slug.toUpperCase().replace(/-/g, '_')}`;
  execSync(`pnpm exec tsx scripts/owner-create.ts ${slug} ${env.get(`${key}_EMAIL`)} --password ${env.get(`${key}_PASSWORD`)}`, { cwd: ROOT, stdio: 'inherit' });
}
console.log('✓ владельцы созданы (логины и пароли — в .env.local, переменные OWNER_*)');
