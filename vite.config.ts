import fs from 'node:fs';
import path from 'node:path';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';
import { VitePWA } from 'vite-plugin-pwa';

import { cloudflare } from "@cloudflare/vite-plugin";

// `vite preview` mirrors the production host rules: deep links inside /s/<slug>/ return that
// studio's own shell (dist/s/<slug>/index.html), never the generic root page.
function tenantShellPreview(): Plugin {
  return {
    name: 'tenant-shell-preview',
    configurePreviewServer(server) {
      server.middlewares.use((req, _res, next) => {
        const m = req.url?.match(/^\/s\/([a-z0-9-]+)(\/[^?]*)?(\?.*)?$/);
        if (m) {
          const file = path.join(server.config.build.outDir, decodeURIComponent(m[0].split('?')[0]!));
          const isFile = fs.existsSync(file) && fs.statSync(file).isFile();
          if (!isFile) req.url = `/s/${m[1]}/index.html${m[3] ?? ''}`;
        }
        next();
      });
    },
  };
}

export default defineConfig({
  plugins: [react(), tenantShellPreview(), VitePWA({
    strategies: 'injectManifest',
    srcDir: 'src',
    filename: 'sw.ts',
    injectRegister: false,
    manifest: false, // per-studio manifests are generated by scripts/tenants-build.ts
    injectManifest: {
      globPatterns: ['assets/**/*.{js,css,woff2}'],
      // The worker is copied into /s/<slug>/ — precache URLs must be absolute.
      modifyURLPrefix: { '': '/' },
      maximumFileSizeToCacheInBytes: 3 * 1024 * 1024,
    },
    devOptions: { enabled: false },
  }), cloudflare()],
  resolve: {
    alias: {
      '@': path.resolve(import.meta.dirname, 'src'),
      '@shared': path.resolve(import.meta.dirname, 'shared'),
      '@fn': path.resolve(import.meta.dirname, 'supabase/functions/_shared'),
    },
  },
  server: { port: 5173, strictPort: true },
  preview: { port: 4173, strictPort: true },
  build: { sourcemap: true, chunkSizeWarningLimit: 1200 },
});